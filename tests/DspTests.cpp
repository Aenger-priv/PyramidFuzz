#include <JuceHeader.h>
#include "dsp/FuzzEngine.h"
#include <cmath>
#include <iostream>

using namespace pyramidfuzz::dsp;

namespace
{
double toneGain(double rate, float tone, float high, double frequency)
{
    ToneStack stack;
    stack.prepare(rate, 128, 1);
    double real = 0, imaginary = 0;
    const int settle = int(rate / 2);
    const int window = int(rate / 4);
    for (int i = 0; i < settle + window; ++i)
    {
        const double phase = 2 * juce::MathConstants<double>::pi * frequency * i / rate;
        const float output = stack.processSample(0, float(0.1 * std::sin(phase)), tone, high);
        if (i >= settle)
        {
            real += output * std::sin(phase);
            imaginary += output * std::cos(phase);
        }
    }
    return 2 * std::hypot(real, imaginary) / window / 0.1;
}
}

int main()
{
    int failures = 0;
    const auto check = [&failures](bool condition, const char* message)
    {
        if (! condition) { std::cerr << message << '\n'; ++failures; }
    };

    // The fixed preamp must remain monotonic for hot inputs; its old quadratic
    // skew could fold a sufficiently negative input toward the positive rail.
    for (double rate : {88200.0, 192000.0, 768000.0})
    {
        float previous = -10;
        for (float input : {-10.0f, -1.0f, -.1f, 0.0f, .1f, 1.0f, 10.0f})
        {
            PreGainStage pre;
            pre.prepare(rate, 128, 1);
            float output = 0;
            for (int i = 0; i < int(.01 * rate); ++i) output = pre.processSample(0, input);
            check(std::isfinite(output) && std::abs(output) < 9, "preamp must respect finite supply headroom");
            check(output > previous, "fixed preamp must be monotonic without foldback");
            previous = output;
        }
    }

    // Behavioral regressions complement the independent full AC grid check.
    // They test direction and useful signal flow, not copied circuit constants.
    for (double rate : {44100.0, 48000.0, 96000.0})
    {
        for (float high : {0.0f, 0.5f, 1.0f})
        {
            const auto darkTilt = toneGain(rate, 0, high, 5000) / toneGain(rate, 0, high, 100);
            const auto brightTilt = toneGain(rate, 1, high, 5000) / toneGain(rate, 1, high, 100);
            check(brightTilt > darkTilt * 1.2, "Tone must sweep from dark to bright");
        }
        check(toneGain(rate, 0, 1, 5000) > 2 * toneGain(rate, 0, 0, 5000), "High must extend the low-pass arm's upper response");
        check(toneGain(rate, 1, 1, 1000) > 0.1, "Tone/High maximum must not collapse into near silence");
    }

    // Material distinction is generated by the feedback circuit, including Ge's
    // one/two-junction branches, rather than output gains or a quadratic skew.
    for (double rate : {88200.0, 192000.0, 768000.0})
    {
        double levels[3] {}, even[3] {};
        for (int mode = 0; mode < 3; ++mode)
        {
            FeedbackClipper clip; clip.prepare(rate, 1, true);
            double energy = 0, h2sin = 0, h2cos = 0;
            const int count = int(.3 * rate), start = int(.2 * rate);
            for (int i = 0; i < count; ++i)
            {
                const double phase = 2 * juce::MathConstants<double>::pi * 100 * i / rate;
                const auto r = clip.process(0, {.1 * std::sin(phase), 6200}, float(mode));
                check(std::isfinite(r.output) && std::abs(r.output) < 4.7, "feedback amplifier must respect supply headroom");
                check(std::abs(r.residual) < 1e-9 && r.iterations < 48, "feedback solve must converge");
                if (mode == 0) check(r.diodeCurrent == 0, "Off must open the diode branch");
                if (i >= start)
                {
                    energy += r.output * r.output;
                    h2sin += r.output * std::sin(2 * phase); h2cos += r.output * std::cos(2 * phase);
                }
            }
            levels[mode] = std::sqrt(energy / (count - start));
            even[mode] = 2 * std::hypot(h2sin, h2cos) / (count - start);
        }
        check(levels[0] > 1.5 * levels[1], "Off must retain greater amplifier headroom than silicon");
        check(levels[1] > 1.1 * levels[2], "Ge feedback must clip at a usefully lower level than silicon");
        check(even[2] > 2 * even[1] && even[2] > .005, "one/two Ge branches must produce real asymmetric harmonics");
    }

    // With four physical inversions represented as positive-gain blocks, Q3
    // and Q1 must use the opposite normalized rail orientation from Q4/Q2.
    for (bool selectable : {false, true})
    {
        FeedbackClipper positive, negative;
        positive.prepare(192000, 1, selectable); negative.prepare(192000, 1, selectable);
        double p = 0, n = 0;
        for (int i = 0; i < 96000; ++i)
        {
            p = positive.process(0, {5, 6200}, 0).output;
            n = negative.process(0, {-5, 6200}, 0).output;
        }
        check(selectable ? p < -n : p > -n, "alternating clipping-stage rail orientation must follow the physical inversions");
    }
    OutputStage positiveRecovery, negativeRecovery;
    positiveRecovery.prepare(192000,128,1); negativeRecovery.prepare(192000,128,1);
    check(positiveRecovery.processSample(0,10) < -negativeRecovery.processSample(0,-10),
          "normalized recovery positive headroom must be the supply-side limit");

    // C2, rather than a duplicate C3 blocker, removes recovery-stage DC. Its
    // physical ~1 s time constant needs a longer settling window than 24 Hz.
    OutputStage recovery; recovery.prepare(192000, 128, 1);
    float dcTail = 0;
    for (int i = 0; i < 1920000; ++i) dcTail = recovery.processSample(0, .1f);
    check(std::abs(dcTail) < 1e-4f, "recovery output coupling must reject DC after settling");

    for (const auto rate : { 44100.0, 48000.0, 96000.0 })
        for (int quality = 0; quality < 3; ++quality)
            for (int mode = 0; mode < 3; ++mode)
            {
                FuzzEngine engine;
                FuzzParameters parameters;
                parameters.oversamplingMode = quality;
                parameters.clippingMode = mode;
                engine.updateParameters(parameters);
                engine.prepare(rate, 128, 2);
                juce::AudioBuffer<float> buffer(2, 128);
                double energy = 0.0;
                for (int block = 0; block < 40; ++block)
                {
                    for (int i = 0; i < 128; ++i)
                    {
                        const auto sample = 0.15f * std::sin(static_cast<float>(2.0 * juce::MathConstants<double>::pi * 110.0 * (block * 128 + i) / rate));
                        buffer.setSample(0, i, sample);
                        buffer.setSample(1, i, sample);
                    }
                    engine.processBlock(buffer);
                    for (int i = 0; i < 128; ++i)
                    {
                        const auto left = buffer.getSample(0, i);
                        check(std::isfinite(left) && std::abs(left) <= 8.0f, "output must be finite and bounded");
                        check(std::abs(left - buffer.getSample(1, i)) < 1.0e-6f, "identical channels must match");
                        if (block >= 20) energy += left * left;
                    }
                }
                check(energy > 1.0e-6, "signal must pass through the engine");
            }
    // Rapid diode reversals and hot asymmetric material drive at every host
    // rate/quality. This is a safety/decay regression; host qualification is Step 5.
    for (double rate : {44100.0, 48000.0, 96000.0})
        for (int quality = 0; quality < 3; ++quality)
        {
            FuzzParameters p; p.inputDecibels = 18; p.sustain = 1;
            p.tone = 1; p.high = 1; p.volumeDecibels = -11;
            p.oversamplingMode = quality; p.clippingMode = 2;
            FuzzEngine engine; engine.updateParameters(p); engine.prepare(rate, 128, 2);
            juce::AudioBuffer<float> buffer(2, 128);
            double peak = 0, tail = 0;
            for (int offset = 0; offset < int(9 * rate); offset += 128)
            {
                p.clippingMode = offset < int(.5 * rate) ? (offset / 128) % 3 : 2;
                engine.updateParameters(p);
                for (int i = 0; i < 128; ++i)
                {
                    const double time = (offset + i) / rate;
                    const float x = time < .6 ? float(.8 * std::sin(2 * juce::MathConstants<double>::pi * 82.4 * time)) : 0;
                    buffer.setSample(0,i,x); buffer.setSample(1,i,x);
                }
                engine.processBlock(buffer);
                for (int i = 0; i < 128; ++i)
                {
                    const float x = buffer.getSample(0,i);
                    check(std::isfinite(x), "hot Ge/mode changes must remain finite");
                    check(std::abs(x-buffer.getSample(1,i)) < 1e-6f, "mode changes must preserve channel identity");
                    peak = std::max(peak,double(std::abs(x)));
                    if (offset > int(8.9 * rate)) tail = std::max(tail,double(std::abs(x)));
                }
            }
            check(peak < .9, "default Volume must retain headroom at hot Input/full Sustain");
            check(tail < 1e-4, "asymmetric clipping/mode-change tail must settle without persistent DC");
        }
    return failures == 0 ? 0 : 1;
}
